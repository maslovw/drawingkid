const byId = (id) => LANGUAGES.find((l) => l.id === id);

// The first of the device's preferred languages that the app has, else English.
export function deviceLanguage(preferred = navigator.languages?.length ? navigator.languages : [navigator.language]) {
  for (const tag of preferred) {
    const id = String(tag ?? '').toLowerCase().split('-')[0];
    if (byId(id)) return id;
  }
  return 'en';
}

let current = 'en';
let plurals = new Intl.PluralRules('en-US');

// `choice` is a language id or 'auto'. Returns true if the language changed.
export function setLanguage(choice) {
  const id = byId(choice) ? choice : deviceLanguage();
  if (id === current) return false;
  current = id;
  plurals = new Intl.PluralRules(byId(id).locale);
  document.documentElement.lang = id;
  return true;
}

export const getLanguage = () => current;
export const getLocale = () => byId(current).locale;

// BCP 47 tag for speech recognition: the device's own variant if it speaks the app's
// language (en-GB, fr-CA, …), else the language's main locale.
export function speechLocale() {
  const device = navigator.language || '';
  return device.toLowerCase().split('-')[0] === current ? device : getLocale();
}

export function t(key, params = {}) {
  let value = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (Array.isArray(value)) return value;
  if (typeof value === 'object') value = value[plurals.select(params.count)] ?? value.other;
  return value.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

// Fills marked elements under `root`:
//   data-i18n="key"            text content
//   data-i18n-html="key"       markup (only for the app's own strings)
//   data-i18n-attr="title:key; aria-label:key"
export function applyTranslations(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}
